import { get, head } from "@vercel/blob";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { FileError, assertFileSignature, MAX_FILE_BYTES } from "./policy";

export function localStorageEnabled() {
  return process.env.NODE_ENV !== "production" && process.env.FILE_STORAGE_DRIVER === "local" && process.env.FILE_LOCAL_TEST === "true";
}
function localPath(pathname: string) {
  const directory = process.env.FILE_LOCAL_DIRECTORY;
  if (!localStorageEnabled() || !directory) throw new FileError("File storage is not configured.", 503);
  if (!/^managed\/[a-f0-9-]{36}\/[a-f0-9-]{36}\.(jpg|jpeg|png|webp|pdf)$/.test(pathname)) throw new FileError("Invalid storage path.");
  const root = resolve(directory);
  const path = resolve(root, pathname);
  if (!path.startsWith(`${root}/`)) throw new FileError("Invalid storage path.");
  return path;
}
export function storageConfigured() {
  if (process.env.FILE_STORAGE_DRIVER === "local") return localStorageEnabled() && Boolean(process.env.FILE_LOCAL_DIRECTORY);
  return Boolean(process.env.BLOB_READ_WRITE_TOKEN);
}
export async function writeLocalUpload(pathname: string, contentType: string, bytes: Uint8Array) {
  if (bytes.length > MAX_FILE_BYTES) throw new FileError("File is too large.", 413);
  assertFileSignature(contentType, bytes);
  const path = localPath(pathname);
  await mkdir(dirname(path), { recursive: true, mode: 0o700 });
  await writeFile(path, bytes, { flag: "wx", mode: 0o600 });
}

/** Pathname is generated by our server, never a caller-provided URL. */
export async function inspectStoredUpload(pathname: string, expected: { contentType: string; byteSize: number }) {
  if (localStorageEnabled()) {
    const bytes = await readFile(localPath(pathname));
    if (bytes.length !== expected.byteSize) throw new FileError("The uploaded file size does not match.");
    assertFileSignature(expected.contentType, bytes.subarray(0, 16));
    return;
  }
  if (!storageConfigured()) throw new FileError("Private file storage is not configured.", 503);
  const info = await head(pathname);
  const host = new URL(info.url).hostname;
  if (!host.endsWith(".private.blob.vercel-storage.com") || info.pathname !== pathname) throw new FileError("The upload is not in private storage.");
  if (info.size !== expected.byteSize || info.size > MAX_FILE_BYTES || info.contentType !== expected.contentType) throw new FileError("The uploaded file metadata does not match.");
  const stored = await get(pathname, { access: "private" });
  if (!stored || stored.statusCode !== 200 || !stored.stream) throw new FileError("Upload not found. Try again.", 404);
  const reader = stored.stream.getReader();
  const prefix = new Uint8Array(16);
  let length = 0;
  try {
    while (length < 16) {
      const { value, done } = await reader.read();
      if (done) break;
      const amount = Math.min(value.length, 16 - length);
      prefix.set(value.subarray(0, amount), length); length += amount;
    }
  } finally { await reader.cancel(); }
  assertFileSignature(expected.contentType, prefix.subarray(0, length));
}
export async function readStoredFile(pathname: string): Promise<ReadableStream<Uint8Array>> {
  if (localStorageEnabled()) {
    const bytes = await readFile(localPath(pathname));
    return new ReadableStream({ start(controller) { controller.enqueue(bytes); controller.close(); } });
  }
  const stored = await get(pathname, { access: "private" });
  if (!stored || stored.statusCode !== 200 || !stored.stream) throw new FileError("File not found.", 404);
  return stored.stream;
}
